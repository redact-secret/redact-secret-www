// Generates src/contracts/<schemaVersion>.ts from schemas/<schemaVersion>.schema.json
// with json-schema-to-typescript. The schemas are the only hand-kept
// definition of the data; these types are never edited by hand.
//
//   npm run data:types            regenerate
//   npm run check:data-types      fail if the committed types drift from the schemas (CI)
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { compile } from 'json-schema-to-typescript';
import { loadSchemas, root, schemaDir, SCHEMA_BASE } from './data/contracts.mjs';

const check = process.argv.includes('--check');
const outDir = join(root, 'src', 'contracts');

// Resolve every https://www.redactsecret.com/schemas/* $ref from schemas/ on
// disk: generation never touches the network.
const $refOptions = {
  resolve: {
    http: false,
    local: {
      order: 1,
      canRead: (file) => file.url.startsWith(SCHEMA_BASE),
      read: (file) => readFileSync(join(schemaDir, file.url.slice(SCHEMA_BASE.length).split('#')[0]), 'utf8'),
    },
  },
};

const banner = (file) =>
  `/* eslint-disable */\n/**\n * GENERATED by scripts/gen-data-types.mjs from schemas/${file}.\n * Do not edit: change the schema and run \`npm run data:types\`.\n */`;

// Conditional rules (if/then/else, not) constrain which combinations are
// valid, not the shape; Ajv enforces them. Stripping them keeps the generated
// types plain objects instead of intersections with `unknown`.
function shapeOnly(node) {
  if (Array.isArray(node)) return node.map(shapeOnly);
  if (!node || typeof node !== 'object') return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === 'if' || k === 'then' || k === 'else' || k === 'not' || k === '$comment') continue;
    // A description beside a $ref would mint a numbered copy of the referenced type.
    if (k === 'description' && node.$ref) continue;
    out[k] = shapeOnly(v);
  }
  if (out.allOf) {
    out.allOf = out.allOf.filter((s) => Object.keys(s).length);
    if (!out.allOf.length) delete out.allOf;
  }
  return out;
}

const { documents } = loadSchemas();
const expected = new Map();
for (const [version, { file, schema }] of documents) {
  const ts = await compile(shapeOnly(schema), schema.title, {
    bannerComment: banner(file),
    cwd: schemaDir,
    additionalProperties: false,
    unreachableDefinitions: false,
    strictIndexSignatures: true,
    format: true,
    style: { singleQuote: true, printWidth: 120 },
    $refOptions,
  });
  expected.set(`${version}.ts`, ts);
}
// Types only, one namespace per contract (release-v1 → ReleaseV1): several
// schemas share $defs (Freshness, Source, ...), so they are not merged.
const namespace = (v) => v.replace(/(^|-)([a-z0-9])/g, (_m, _d, c) => c.toUpperCase());
expected.set(
  'index.ts',
  `${banner('*.schema.json')}\n${[...documents.keys()].map((v) => `export type * as ${namespace(v)} from './${v}';`).join('\n')}\n`,
);

if (check) {
  const drift = [];
  for (const [name, ts] of expected) {
    const path = join(outDir, name);
    if (!existsSync(path) || readFileSync(path, 'utf8') !== ts) drift.push(`src/contracts/${name}`);
  }
  const extra = existsSync(outDir) ? readdirSync(outDir).filter((f) => !expected.has(f)) : [];
  for (const f of extra) drift.push(`src/contracts/${f} (no schema)`);
  if (drift.length) {
    for (const d of drift) console.error(`check:data-types: ${d} does not match schemas/ — run npm run data:types`);
    process.exit(1);
  }
  console.log(`check:data-types: ${expected.size} files match schemas/`);
} else {
  mkdirSync(outDir, { recursive: true });
  for (const [name, ts] of expected) writeFileSync(join(outDir, name), ts);
  console.log(`data:types: wrote ${[...expected.keys()].map((n) => `src/contracts/${n}`).join(', ')}`);
}
